#!/usr/bin/env python3
"""
scripts/make_asset_index.py — a contact sheet and a manifest for assets/.

    python3 scripts/make_asset_index.py

Writes `assets/index.html` with every SVG inlined, so the sheet renders with no network
and no relative paths — the preview pane is sandboxed and would show broken images
otherwise. Also writes `assets/README.md`: what each asset is for and where it is used.

Run after make_assets.py and make_diagrams.py.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
SVG = ASSETS / "svg"

NOTES = {
    "logo-primary": ("Logo", "The lockup on paper. READMEs, slides, the video's title card."),
    "logo-primary-transparent": ("Logo", "Same lockup with no background, for white pages."),
    "logo-mono-white": ("Logo", "Reversed lockup for dark backgrounds."),
    "logo-wordmark-only": ("Logo", "Name only, where the mark is already present."),
    "logo-mark": ("Logo", "The mark alone."),
    "logo-mark-on-paper": ("Logo", "The mark on a paper tile, for grid layouts."),
    "app-icon": ("App", "512 square. Avatars, store listings, Devpost upload."),
    "favicon": ("App", "256 square. Source for the tab icon."),
    "og-card": ("Card", "1200x630 link preview for social and chat."),
    "devpost-thumbnail": ("Card", "1280x720 listing thumbnail. Upload this one to Devpost."),
    "diagram-flow": ("Diagram", "The decision in one read: month + purchase, projection, "
                                "floor test, three outcomes."),
    "diagram-verdicts": ("Diagram", "The same $249 across three months, with the real copy."),
    "diagram-defer": ("Diagram", "The hero path: invoice on payday, ship on payment."),
    "diagram-architecture": ("Diagram", "Four layers, one boundary, zero dependencies."),
    "diagram-ai-boundary": ("Diagram", "Why the model cannot decide anything."),
    "diagram-gate": ("Diagram", "Why a tampered approval cannot move money."),
    "diagram-clusters": ("Diagram", "Where the idea sits in a field of 549 repos."),
}

PAGE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Second Thought - assets</title>
<style>
  body {{ margin:0; background:#eef0f3; color:#14181f;
         font:16px/1.5 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif; }}
  .wrap {{ max-width:1180px; margin:0 auto; padding:40px 24px 80px; }}
  h1 {{ font-size:26px; margin:0 0 6px; letter-spacing:-.01em; }}
  p.sub {{ color:#5b6472; margin:0 0 8px; }}
  h2 {{ font-size:12px; text-transform:uppercase; letter-spacing:.1em; color:#5b6472;
        margin:44px 0 14px; }}
  .card {{ background:#fff; border:1px solid #dfe3e9; border-radius:14px; padding:18px;
           margin:0 0 18px; }}
  .card h3 {{ margin:0 0 2px; font-size:16px; }}
  .card .meta {{ color:#7a828f; font:12px "DejaVu Sans Mono",monospace; margin:0 0 14px; }}
  .card .art {{ background:#f6f7f9; border-radius:8px; overflow:hidden;
                display:flex; align-items:center; justify-content:center; padding:10px; }}
  .card svg {{ max-width:100%; height:auto; }}
  .dark {{ background:#14181f; }}
  .row {{ display:grid; grid-template-columns:1fr 1fr; gap:18px; }}
  footer {{ color:#7a828f; font-size:13px; border-top:1px solid #dfe3e9; padding-top:16px; }}
</style></head>
<body><div class="wrap">
<h1>Second Thought — asset sheet</h1>
<p class="sub">Every asset in this folder, drawn from one palette so the video, the README and
the product page cannot drift apart.</p>
<p class="sub">{count} assets · SVG source in <code>svg/</code> · rasters in <code>png/</code> ·
regenerate with <code>scripts/make_assets.py</code> and <code>scripts/make_diagrams.py</code></p>
{sections}
<footer>Generated by <code>scripts/make_asset_index.py</code>. The SVGs are inlined here so the
sheet renders with no network access.</footer>
</div></body></html>
"""


def main() -> int:
    if not SVG.exists():
        print("no assets/svg yet — run make_assets.py and make_diagrams.py first")
        return 1
    files = sorted(SVG.glob("*.svg"))
    groups: dict[str, list[str]] = {}
    for f in files:
        kind = NOTES.get(f.stem, ("Other", ""))[0]
        groups.setdefault(kind, []).append(f.stem)

    blocks, manifest = [], []
    for kind in ("Logo", "App", "Card", "Diagram"):
        if kind not in groups:
            continue
        blocks.append(f"<h2>{kind}s</h2>")
        items = []
        for stem in groups[kind]:
            svg = (SVG / f"{stem}.svg").read_text()
            svg = svg.replace('width="', 'data-w="', 1).replace('data-w="', 'width="', 1)
            png = (ASSETS / "png" / f"{stem}.png")
            size = f"{png.stat().st_size // 1024} KB png" if png.exists() else "svg only"
            note = NOTES.get(stem, ("", ""))[1]
            item = (f'<div class="card"><h3>{stem}</h3>'
                    f'<p class="meta">{kind.lower()} · {size}</p>'
                    f'<div class="art{" dark" if "mono-white" in stem or "app-icon" in stem else ""}">'
                    f'{svg}</div><p class="sub" style="margin:12px 0 0">{note}</p></div>')
            items.append(item)
            manifest.append(f"| `{stem}` | {kind.lower()} | {note} |")
        if kind in ("App", "Card", "Logo") and len(items) > 1:
            blocks.append('<div class="row">' + "".join(items) + "</div>")
        else:
            blocks.extend(items)

    html = PAGE.format(count=len(files), sections="\n".join(blocks))
    (ASSETS / "index.html").write_text(html)

    readme = ["# Assets", "",
              "Generated, not hand-drawn. Regenerate everything with:", "",
              "```bash",
              "python3 scripts/make_assets.py        # logo, icon, cards",
              "python3 scripts/make_diagrams.py      # the four story diagrams",
              "python3 scripts/make_diagrams_tech.py # the three system diagrams",
              "python3 scripts/make_asset_index.py   # this folder's index and README",
              "```", "",
              "Palette and type scale live in `scripts/asset_kit.py`, so every asset matches "
              "the product page: ink `#14181f`, paper `#f6f7f9`, and one colour per verdict "
              "— offer `#0f7b4f`, defer `#8a5a00`, decline `#8c2f39`.", "",
              "SVG is the source of truth; PNG is rasterised at 1.6–3x with cairosvg. Nothing "
              "here loads a font or an image from the network.", "",
              "| Asset | Kind | Where it is used |", "|---|---|---|"]
    readme += sorted(manifest, key=lambda line: line.lower())
    readme += ["", "Open `index.html` to look at the whole set at once.", ""]
    (ASSETS / "README.md").write_text("\n".join(readme))
    print(f"  ✓ assets/index.html ({len(html)//1024} KB) and assets/README.md "
          f"— {len(files)} assets")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
