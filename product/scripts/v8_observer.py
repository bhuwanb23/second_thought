#!/usr/bin/env python3
"""
scripts/v8_observer.py — run the outside-eye rehearsal, and score it honestly.

    python3 scripts/v8_observer.py --precheck --url https://<app>.onrender.com
    python3 scripts/v8_observer.py --record  --url https://<app>.onrender.com
    python3 scripts/v8_observer.py --report

V8's pass line is specific: **they reach a DECLINE or DEFER and can explain why, in
their own words, within about two minutes, unaided.** So this records exactly
those three things — seconds, whether they explained it, and whether you helped —
and refuses to count a session you narrated.

`--precheck` exists because a rehearsal that dies on a 500 wastes the one person
who agreed to sit with you.

The confusion notes are the point of the exercise. They are what the video script
should say instead.
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
LOG = ROOT / "docs" / "plan" / "v8_rehearsals.jsonl"
DOC = ROOT / "docs" / "plan" / "V8_outside_eye.md"
MARK_START = "<!-- V8 RESULTS START · generated by scripts/v8_observer.py -->"
MARK_END = "<!-- V8 RESULTS END -->"

PASS_SECONDS = 120
ok = fail = 0


def check(label: str, passed: bool, detail: str = "") -> None:
    global ok, fail
    if passed:
        ok += 1
        print(f"  ✓ {label}" + (f"  {detail}" if detail else ""))
    else:
        fail += 1
        print(f"  ✗ {label}" + (f"  [{detail}]" if detail else ""))


def fetch(url: str, path: str) -> tuple:
    try:
        with urllib.request.urlopen(url.rstrip("/") + path, timeout=30) as r:
            return r.status, r.read()
    except urllib.error.HTTPError as exc:
        return exc.code, exc.read()
    except urllib.error.URLError as exc:
        print(f"  ✗ cannot reach {url}: {exc.reason}")
        raise SystemExit(2)


def precheck(url: str) -> int:
    print(f"\nV8 preflight against {url}\n")
    status, body = fetch(url, "/")
    check("the page loads", status == 200, f"HTTP {status}")
    text = body.decode("utf-8", "replace")
    n = text.count('data-persona="')          # the buttons, not the JS selector
    check("three months are on the first screen", n == 3, f"{n} found")
    check("it needs no network of its own",
          not any(x in text for x in ('src="http', 'href="http', "@import")))
    check("both badges are shown", "AI ·" in text and "PAYMENTS ·" in text)
    check("it says the money is simulated", "Nothing is charged" in text)

    status, body = fetch(url, "/healthz")
    health = json.loads(body)
    check("/healthz answers with booleans only",
          set(health) == {"status", "ai_mode", "payments_mode", "checks"})
    print(f"\n  ai_mode     {health.get('ai_mode')}")
    print(f"  payments    {health.get('payments_mode')}")
    if health.get("ai_mode") == "llm-mock":
        print("  ! the badge will read AI · LLM-MOCK. That is honest, but if a key is")
        print("    meant to be set, fix it before the tester sits down.")
    print(f"\n  {ok} passed, {fail} failed\n")
    return 0 if fail == 0 else 1


def record(url: str) -> int:
    print("\nV8 rehearsal — read the protocol aloud, then hand over the laptop.")
    print("─" * 70)
    print("  Give them: the URL, the repo link, the README. Nothing else.")
    print("  Do not narrate. Do not point. If you help, the session does not count.\n")

    tester = input("  Who is it — a descriptor, never a name\n  > ").strip() or "tester"
    input("\n  Press Enter when they take the laptop, and start the clock. ")
    started = time.time()
    input("  … let them work. Press Enter the moment they can explain the answer. ")
    seconds = int(time.time() - started)

    verdict = ""
    while verdict not in ("offer", "defer", "decline"):
        verdict = input("  Which answer did they reach? [offer/defer/decline]\n  > ").strip().lower()

    explained = ""
    while explained not in ("yes", "no"):
        explained = input("  In their own words, did they explain WHY correctly? [yes/no]\n  > ").strip().lower()

    help_given = ""
    while help_given not in ("none", "pointed", "explained"):
        help_given = input("  What help did you give? [none/pointed/explained]\n  > ").strip().lower()

    said = input("  What did they say the answer meant? Their words, not yours.\n  > ").strip()
    confusions = []
    print("  Now the stuck points. Blank to stop. Verbatim — where they paused, what")
    print("  they re-read, what they guessed wrong.")
    while True:
        line = input("    confusion > ").strip()
        if not line:
            break
        confusions.append(line)

    entry = {"at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "url": url,
             "tester": tester, "seconds": seconds, "verdict": verdict,
             "explained": explained == "yes", "help": help_given,
             "said": said, "confusions": confusions,
             "pass": explained == "yes" and help_given == "none" and seconds <= PASS_SECONDS}
    LOG.parent.mkdir(parents=True, exist_ok=True)
    with LOG.open("a") as fh:
        fh.write(json.dumps(entry, sort_keys=True) + "\n")

    print("\n" + "─" * 70)
    print(f"  {seconds}s · {verdict.upper()} · explained: {explained} · help: {help_given}")
    print(f"  → {'PASS' if entry['pass'] else 'FAIL — this is the finding, not a setback'}")
    print(f"  recorded in {LOG.name}\n")
    return 0


def report() -> int:
    if not LOG.exists():
        print("\nNo rehearsals recorded. V8 has not run.\n")
        return 0
    rows = [json.loads(line) for line in LOG.read_text().splitlines() if line.strip()]
    passed = [r for r in rows if r["pass"]]
    print(f"\nV8 report — {len(rows)} rehearsal(s), {len(passed)} passing\n")
    for r in rows:
        print(f"  {r['tester']:<20} {r['verdict']:<8} {r['seconds']:>4}s  "
              f"explained={r['explained']}  help={r['help']}  "
              f"{'PASS' if r['pass'] else 'FAIL'}")
        if r["said"]:
            print(f"    they said: “{r['said']}”")
        for c in r["confusions"]:
            print(f"    stuck: {c}")
    if rows:
        print(f"\n  median time to explain: {statistics.median(r['seconds'] for r in rows):.0f}s "
              f"(pass line {PASS_SECONDS}s)")
        reached = {r["verdict"] for r in rows}
        print(f"  verdicts reached: {sorted(reached)}")
        if not ({"defer", "decline"} & reached):
            print("  ! nobody reached DEFER or DECLINE — point them at Ben or Cleo next time")

    write_block(rows)
    print(f"\n  written into {DOC.name}\n")
    return 0 if len(passed) == len(rows) else 1


def write_block(rows: list[dict]) -> None:
    lines = [MARK_START, "",
             f"**{len(rows)} rehearsal(s), {sum(1 for r in rows if r['pass'])} passing.** "
             f"Pass line: explained unaided in under {PASS_SECONDS}s.", ""]
    if rows:
        lines += ["| Tester | Answer | Seconds | Explained it | Help given | Result |",
                  "|---|---|---|---|---|---|"]
        for r in rows:
            lines.append(f"| {r['tester']} | {r['verdict'].upper()} | {r['seconds']} | "
                         f"{'yes' if r['explained'] else 'no'} | {r['help']} | "
                         f"{'✅' if r['pass'] else '❌'} |")
        confusions = [c for r in rows for c in r["confusions"]]
        if confusions:
            lines += ["", "**Stuck points — the video script's weak spots:**", ""]
            lines += [f"- {c}" for c in confusions]
        said = [r["said"] for r in rows if r["said"]]
        if said:
            lines += ["", "**In their words:**", ""] + [f"- “{s}”" for s in said]
    lines += ["", MARK_END]
    block = "\n".join(lines)
    if DOC.exists():
        text = DOC.read_text()
        if MARK_START in text and MARK_END in text:
            text = text.split(MARK_START)[0] + block + text.split(MARK_END)[1]
        else:
            text = text.rstrip() + "\n\n" + block + "\n"
        DOC.write_text(text)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="")
    ap.add_argument("--precheck", action="store_true")
    ap.add_argument("--record", action="store_true")
    ap.add_argument("--report", action="store_true")
    args = ap.parse_args(argv)
    if args.precheck:
        if not args.url:
            print("--precheck needs --url", file=sys.stderr)
            return 2
        return precheck(args.url)
    if args.record:
        if not args.url:
            print("--record needs --url", file=sys.stderr)
            return 2
        return record(args.url)
    if args.report:
        return report()
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
