#!/usr/bin/env python3
"""
scripts/v7_verdict.py — apply the pre-committed rules, mechanically.

    python3 scripts/v7_verdict.py                 # read the log, decide, print
    python3 scripts/v7_verdict.py --write          # also render the table into P2

The rules were written down before anyone was asked. This script is the reason
they stay that way: it counts, it matches a row, and it prints the only claim the
submission is allowed to make. There is no flag to soften a result.

Two things it deliberately refuses to do:

  * score a discarded row (a pitched conversation, or someone who has never used
    BNPL) — those are recorded and skipped;
  * round. n is whatever the log says, and a rule that says "0–1 of 5" fires at 1.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
LOG = ROOT / "docs" / "plan" / "v7_conversations.jsonl"
P2 = ROOT / "docs" / "plan" / "P2_five_conversations.md"
MARK_START = "<!-- V7 TABLE START · generated by scripts/v7_verdict.py · do not edit -->"
MARK_END = "<!-- V7 TABLE END -->"


def load(path: Path) -> tuple[list[dict], list[str]]:
    problems = []
    if not path.exists():
        return [], []          # no log is n = 0, not a tamper alarm
    records = [json.loads(line) for line in
               path.read_text(encoding="utf-8").splitlines() if line.strip()]
    prev = "genesis"
    for i, r in enumerate(records, 1):
        if r.get("seq") != i:
            problems.append(f"row {i}: seq is {r.get('seq')} — a row was removed or reordered")
        body = json.dumps({k: v for k, v in r.items() if k != "hash"},
                          sort_keys=True, separators=(",", ":"))
        if hashlib.sha256(body.encode()).hexdigest()[:16] != r.get("hash"):
            problems.append(f"row {i}: hash does not match its contents — edited after writing")
        if r.get("prev") != prev:
            problems.append(f"row {i}: chain broken (expected {prev[:8]}, "
                            f"found {str(r.get('prev'))[:8]})")
        prev = r.get("hash", "")
    return records, problems


def decide(scored: list[dict]) -> tuple[list[str], dict]:
    """Every rule, evaluated. The conservative reading wins a tie — see --explain."""
    n = len(scored)
    fired: list[str] = []
    if n == 0:
        return ["no rows: n = 0"], {"n": 0}

    recall = sum(1 for r in scored if r["recall"] == "yes")
    no_profile = sum(1 for r in scored if r["profile"] == "no")
    patronising = sum(1 for r in scored if r["decline"] == "patronising")
    enabled = sum(1 for r in scored if r["enable"] == "yes")

    if recall >= 4:
        fired.append("R1 · 4–5 of 5 recalled a timing problem unprompted → the problem "
                     "is real and top-of-mind: quote one person, with permission")
    elif recall >= 2:
        fired.append(f"R2 · {recall} of {n} recalled it unprompted → real but not "
                     f"top-of-mind: CHANGE THE HOOK to lead with the explanation gap")
    else:
        fired.append(f"R3 · {recall} of {n} recalled it unprompted → the timing hook is not "
                     f"supported: reframe to safe-amount-only and drop the timing claim")

    if no_profile >= 3:
        fired.append(f"R4 · {no_profile} of {n} would not set up a profile → cold-start risk "
                     f"confirmed: lead the demo with the SAVED profile, onboarding is roadmap")
    if patronising >= 3:
        fired.append(f"R5 · {patronising} of {n} called the decline patronising → rewrite the "
                     f"copy to 'what fits' framing; the mechanic does not change")

    return fired, {"n": n, "recall": recall, "no_profile": no_profile,
                   "patronising": patronising, "enabled": enabled}


def claim(counts: dict) -> str:
    n = counts.get("n", 0)
    if n >= 5:
        extra = (f", {counts['recall']} recalled this unprompted"
                 if counts.get("recall") else "")
        return f"tested with five shoppers{extra}"
    if n == 4:
        return "tested with four shoppers"
    if n == 3:
        return "tested with three shoppers"
    if n == 2:
        return "two conversations — do not generalise from them"
    return "DELETE every hint of user validation; the product is researched, not tested"


def table(records: list[dict]) -> str:
    icon = {"yes": "✅", "no": "—"}
    rows = ["| # | Who (shape, not name) | Timing recalled unprompted? | No explanation "
            "given? | Would set up a profile? | Decline: helpful or patronising? | "
            "Ship-after-pay OK? | Would enable it? | Verbatim that matters most |",
            "|---|---|---|---|---|---|---|---|---|"]
    for r in records:
        if r.get("discarded"):
            rows.append(f"| {r['seq']} | ~~{r['who']}~~ | DISCARDED — "
                        f"{'not a BNPL user' if not r.get('eligible') else 'pitched before asking'} |"
                        " | | | | | |")
            continue
        rows.append(f"| {r['seq']} | {r['who']} | {r['recall']} | {r['explained']} | "
                    f"{r['profile']} | {r['decline']} | {r['ship']} | {r['enable']} | "
                    f"“{r['verbatim']}” |")
    return "\n".join(rows)


def _looks_synthetic(records: list[dict]) -> bool:
    """Fixture rows are labelled as such and must never reach the real document."""
    for r in records:
        for value in r.values():
            if isinstance(value, str) and "synthetic" in value.lower():
                return True
    return False


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--log", default=str(LOG))
    ap.add_argument("--write", action="store_true",
                    help="render the table into P2_five_conversations.md between markers")
    ap.add_argument("--force", action="store_true",
                    help="write even if the log looks synthetic — for throwaway copies only")
    ap.add_argument("--explain", action="store_true",
                    help="show how overlapping rules were resolved")
    args = ap.parse_args(argv)

    records, problems = load(Path(args.log))
    print(f"\nSecond Thought — V7 verdict\n{'─' * 70}")
    if problems:
        print("\n  THE LOG IS NOT TRUSTWORTHY:")
        for p in problems:
            print(f"    ✗ {p}")
        print("\n  Nothing is decided from a log that has been edited. "
              "Rebuild it from capture, or delete it and report n = 0.\n")
        return 1

    scored = [r for r in records if not r.get("discarded")]
    dropped = len(records) - len(scored)
    print(f"\n  rows recorded   {len(records)}   scored {len(scored)}"
          + (f"   discarded {dropped}" if dropped else ""))

    if len(records) >= 2:
        stamps = [r["at"] for r in records]
        if len(set(stamps)) < len(stamps) - 1:
            print("  ! several rows share a timestamp — they may have been entered together")

    fired, counts = decide(scored)
    print("\n  rules that fire:")
    for line in fired:
        print(f"    → {line}")
    if args.explain:
        print("\n  overlap note: '3–5 of 5' appears in VALIDATION_CONVERSATIONS.md as the "
              "'strongest available result',\n  while '2–3 of 5 → change the hook' appears in "
              "both documents. At 3 of 5 these conflict.\n  The stricter row wins here, because "
              "pre-commitment only means something if the unflattering\n  reading is the default. "
              "If you would rather it went the other way, that decision has to be\n  made in "
              "writing *before* the first conversation.")

    print(f"\n  THE ONLY PERMITTED CLAIM:\n    “{claim(counts)}”")
    print("\n  required changes:")
    if counts.get("n", 0) >= 2:
        print("    · update README, video script and the C02 header to that exact wording")
    if counts.get("n", 0) >= 3 and counts.get("recall", 0) >= 4:
        print("    · ask one person for permission to quote them, first name or descriptor only")
    if counts.get("n", 0) == 0:
        print("    · delete every hint of user validation from README and video")

    print("\n" + table(records) + "\n")

    if args.write:
        if _looks_synthetic(records) and not args.force:
            print("  ✗ REFUSING TO WRITE: the log contains rows marked synthetic.\n"
                  "    Fixture data must never reach the document that goes in the repo.\n"
                  "    (--force overrides, for a throwaway copy only.)\n")
            return 3
        write_table(P2, records, fired, claim(counts))
        print(f"  table written into {P2.relative_to(ROOT)}")
    else:
        print("  (--write renders this into P2_five_conversations.md)")
    return 0


def write_table(path: Path, records: list[dict], fired: list[str], claim_text: str) -> None:
    block = "\n".join([
        MARK_START,
        f"\n**Generated {len(records)} row(s).** The only permitted claim: "
        f"**“{claim_text}”**\n",
        *[f"> {line}\n" for line in fired],
        "",
        table(records),
        "",
        MARK_END,
    ])
    original = path.read_text(encoding="utf-8") if path.exists() else ""
    if MARK_START in original and MARK_END in original:
        head = original.split(MARK_START)[0]
        tail = original.split(MARK_END)[1]
        path.write_text(head + block + tail, encoding="utf-8")
    else:
        path.write_text(
            original.rstrip() + "\n\n---\n\n## V7 — the table, as run\n\n"
            + block + "\n", encoding="utf-8")


if __name__ == "__main__":
    raise SystemExit(main())
