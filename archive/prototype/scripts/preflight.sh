#!/usr/bin/env bash
# Pre-submission checks. Run from the prototype directory.
set -uo pipefail
fail=0
ok(){ printf '  ok    %s\n' "$1"; }
bad(){ printf '  FAIL  %s\n' "$1"; fail=1; }

echo "Second Thought — preflight"

[ -f LICENSE ] || [ -f ../LICENSE ] && ok "LICENSE present" || bad "no LICENSE file"
grep -qiE "^(MIT|Apache|BSD|GPL|Mozilla)" LICENSE ../LICENSE 2>/dev/null \
  && ok "LICENSE is a recognised type" || bad "LICENSE type not recognised"

[ -f .env.example ] && ok ".env.example present" || bad ".env.example missing"
git check-ignore -q .env 2>/dev/null && ok ".env is gitignored" || bad ".env not gitignored"

if git ls-files | grep -qE '(^|/)\.env$'; then bad ".env is COMMITTED"; else ok ".env not committed"; fi

hits=$(git grep -nEI '(sk-[A-Za-z0-9]{16,}|A[A-Za-z0-9_-]{80,}|client_secret\s*=\s*["'"'"'][^"'"'"']{8,})' -- . 2>/dev/null | grep -v '\.example' | head -5)
[ -z "$hits" ] && ok "no obvious secrets in tracked files" || { bad "possible secret:"; echo "$hits"; }

python3 -m unittest discover -s tests -q 2>/dev/null && ok "test suite passes" || bad "tests fail"

grep -q "Orders v2\|AUTHORIZE" README.md && ok "README names the PayPal APIs" || bad "README lacks API names"
grep -qi "sandbox only" README.md && ok "README states sandbox-only" || bad "README lacks sandbox-only statement"
grep -qi "what is simulated" README.md && ok "README labels simulated parts" || bad "README does not label simulated parts"
grep -q "/healthz" Dockerfile render.yaml 2>/dev/null && ok "health check wired" || bad "no health check"

# no source file may exceed 300 lines — keeps the codebase reviewable
OVER=$(wc -l *.py tests/*.py 2>/dev/null | awk '$2!="total" && $1>300 {print $2}')
if [ -z "$OVER" ]; then ok "every file is under 300 lines"; else bad "over 300 lines: $OVER"; fi

# the operator-only diagnostics endpoint must be gated
grep -q "DIAG_TOKEN" render.yaml .env.example 2>/dev/null && ok "diagnostics token wired" \
  || warn "DIAG_TOKEN not declared"

# HMAC secret must not ship as the documented default in a deployed config
grep -q "generateValue: true" render.yaml 2>/dev/null && ok "approval secret generated by the platform" \
  || warn "render.yaml does not generate APPROVAL_SECRET"

# disposable per-visitor state must never be committed
if git ls-files --error-unmatch profiles.json ledger.json >/dev/null 2>&1; then
  bad "session state committed (profiles.json / ledger.json)"
else
  ok "no session state in git"
fi

echo
[ $fail -eq 0 ] && echo "ALL CHECKS PASSED" || echo "FIX THE FAILURES ABOVE"
exit $fail
